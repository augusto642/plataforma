/** Faixa de exibição de um XP total (última faixa cujo minXp foi atingido). */
export function bandForXp(xp: number): XpBandInfo {
  let current = XP_BANDS[0];
  for (const band of XP_BANDS) {
    if (xp >= band.minXp) current = band;
  }
  return current;
}

